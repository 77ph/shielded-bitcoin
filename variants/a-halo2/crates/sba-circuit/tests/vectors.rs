//! The pinned test vectors of docs/TEST_VECTORS-A.md (family A).
//!
//! `pinned_vectors_match_the_document` fails whenever the code stops
//! reproducing the document, so the document is a regression-locked
//! cross-implementation anchor rather than a snapshot. Regenerate it with
//! `cargo test -p sba-circuit --release --test vectors -- --ignored --nocapture`
//! (and bump the profile version: a changed vector is a changed profile).
//! The test lives in the circuit crate so that the verifying-key identifier
//! is part of the lock.

use ff::PrimeField;
use sha2::{Digest, Sha256};

use sba_circuit::TransferParams;
use sba_core::address::Network;
use sba_core::envelope::{TransferBody, bytes_to_fp_254};
use sba_core::keys::{Seed, WalletKeys};
use sba_core::note::{NotePlaintext, encrypt_note, note_leaf, nullifier};
use sba_core::recovery::{RecoveryEntry, binding_digest, encrypt_recovery};
use sba_core::tree::{DEPTH, EMPTY_ROOTS};
use sba_primitives::Fp;
use sba_primitives::diversify::diversify_hash;
use sba_primitives::encoding::{fp_to_bytes, point_to_bytes};
use sba_primitives::poseidon::hash;
use sba_primitives::scalar::scalar_to_bytes;
use sba_primitives::tags;

fn h(f: &Fp) -> String {
    hex::encode(fp_to_bytes(f))
}

fn render() -> String {
    let mut out = String::new();
    macro_rules! println {
        () => { out.push_str("\n") };
        ($($arg:tt)*) => {{ out.push_str(&format!($($arg)*)); out.push_str("\n"); }};
    }
    println!("# Test vectors, family A (profile draft a-0.3)\n");
    println!(
        "Generated by `variants/a-halo2/crates/sba-circuit/tests/vectors.rs`. All field elements are 32-byte little-endian hex in the Pallas base field; points are 32-byte compressed Pallas points (`docs/PROFILE-A.md`). `PH_A` is Poseidon in the halo2 constant-length mode with the tag as the first input.\n"
    );

    println!("## Poseidon\n");
    println!("| Input | Output |\n|---|---|");
    println!(
        "| `PH_A(0, [0, 0])` | `{}` |",
        h(&hash(Fp::from(0u64), &[Fp::from(0u64), Fp::from(0u64)]))
    );
    println!(
        "| `PH_A(1, [2, 3, 4])` | `{}` |",
        h(&hash(
            Fp::from(1u64),
            &[Fp::from(2u64), Fp::from(3u64), Fp::from(4u64)]
        ))
    );
    println!(
        "| `E_1 = PH_A(T_NODE, [0, 0])` | `{}` |",
        h(&EMPTY_ROOTS[1])
    );
    println!(
        "| `E_32` (empty tree root) | `{}` |",
        h(&EMPTY_ROOTS[DEPTH])
    );
    println!();

    println!("## Domain tags\n");
    println!("| Tag | Label | `Fp` |\n|---|---|---|");
    for (name, label) in tags::ALL {
        println!(
            "| `{name}` | `{label}` | `{}` |",
            h(&tags::tag(label.as_bytes()))
        );
    }
    println!();

    println!("## DiversifyHash\n");
    println!("| `d` (hex) | Result |\n|---|---|");
    for i in 0u8..6 {
        let mut d = [0u8; 11];
        d[0] = i;
        match diversify_hash(&d) {
            Some(p) => println!(
                "| `{}` | `{}` |",
                hex::encode(d),
                hex::encode(point_to_bytes(&p))
            ),
            None => println!("| `{}` | invalid |", hex::encode(d)),
        }
    }
    println!();

    let seed = Seed([1u8; 32]);
    let k = WalletKeys::from_seed(&seed);
    println!("## Key hierarchy for seed `{}`\n", hex::encode(seed.0));
    println!("| Key | Value |\n|---|---|");
    println!("| `sk_master` | `{}` |", hex::encode(k.sk_master));
    println!("| `sk_spend` (`Fp`) | `{}` |", h(&k.sk_spend));
    println!("| `vk_out` | `{}` |", hex::encode(k.ovk.0));
    println!("| `sk_nf` | `{}` |", h(&k.sk_nf));
    println!("| `vk_in` | `{}` |", h(&k.ivk.vk_in));
    println!(
        "| `sk_view` (scalar, LE) | `{}` |",
        hex::encode(scalar_to_bytes(&k.ivk.sk_view))
    );
    let (i, addr) = k.ivk.find_address(0);
    println!("| first valid receive path | `{i}` |");
    println!("| `d` | `{}` |", hex::encode(addr.d));
    println!("| `pk_d` | `{}` |", hex::encode(point_to_bytes(&addr.pk_d)));
    println!("| address (signet) | `{}` |", addr.encode(Network::Signet));
    println!(
        "| address (mainnet) | `{}` |",
        addr.encode(Network::Mainnet)
    );
    println!();

    let pt = NotePlaintext {
        value: 123_456,
        d: addr.d,
        rseed: Fp::from(2u64),
    };
    let (pk_eph, ct) = encrypt_note(&pt, &addr.pk_d).unwrap();
    let const_salt: [u8; 32] = Sha256::digest(b"sb-a/v1/const_salt/vectors").into();
    let salt_fe = bytes_to_fp_254(&const_salt);
    println!("## Note `(v = 123456, d above, rseed = 2)` to that address\n");
    println!("| Value | Hex |\n|---|---|");
    println!("| `m_0` | `{}` |", h(&pt.m0()));
    println!("| `rho` | `{}` |", h(&pt.rho()));
    println!(
        "| `sk_eph` (scalar, LE) | `{}` |",
        hex::encode(scalar_to_bytes(&pt.sk_eph()))
    );
    println!("| `pk_eph` | `{}` |", hex::encode(point_to_bytes(&pk_eph)));
    println!("| `ct_note` | `{}` |", hex::encode(ct.to_bytes()));
    println!(
        "| `const_salt = SHA-256(\"sb-a/v1/const_salt/vectors\")` | `{}` |",
        hex::encode(const_salt)
    );
    println!("| `const_salt` as `Fp` | `{}` |", h(&salt_fe));
    println!(
        "| `leaf` with `h_body = 3`, `j = 0` | `{}` |",
        h(&note_leaf(&salt_fe, &Fp::from(3u64), 0, &pk_eph, &ct))
    );
    println!(
        "| `nf` with `pos = 5` | `{}` |",
        h(&nullifier(&k.sk_nf, &pt.rho(), 5))
    );
    println!();

    let entries = [
        RecoveryEntry {
            pk_d: addr.pk_d,
            sk_eph: pt.sk_eph(),
        },
        RecoveryEntry {
            pk_d: addr.pk_d,
            sk_eph: pt.sk_eph(),
        },
    ];
    let digest = binding_digest(&[pk_eph, pk_eph], &[ct, ct]);
    let ct_out = encrypt_recovery(&k.ovk, &digest, &entries);
    let body = TransferBody {
        h_anchor: 100,
        nullifiers: [Fp::from(1u64), Fp::from(2u64)],
        pk_eph: [pk_eph, pk_eph],
        ct_note: [ct, ct],
        ct_out,
    };
    println!("## Transfer body (`h_anchor = 100`, `nf = [1, 2]`, the note above twice)\n");
    println!("| Value | Hex |\n|---|---|");
    println!("| recovery binding digest | `{}` |", hex::encode(digest));
    println!("| `ct_out` | `{}` |", hex::encode(ct_out));
    println!(
        "| `body_bytes` ({} bytes) | `{}` |",
        body.to_bytes().len(),
        hex::encode(body.to_bytes())
    );
    println!(
        "| `h_body` under `const_salt` above (bits 254 and 255 cleared) | `{}` |",
        h(&body.h_body(&const_salt))
    );
    println!();

    println!("## Halo 2 verifying key\n");
    let params = TransferParams::build().unwrap();
    println!(
        "`vk_id` of the transfer circuit at `k = 14` over the deterministic IPA parameters (the verifying key hashed into a Blake2b transcript, one squeezed challenge; `sba-circuit::proof::vk_id`): `{}`. Deployment profiles pin it as `transfer_vk_id`.\n",
        hex::encode(params.vk_id())
    );
    println!("Field modulus check: `p = {}`.", Fp::MODULUS);
    out
}

#[test]
#[ignore]
fn print_vectors() {
    print!("{}", render());
}

#[test]
fn pinned_vectors_match_the_document() {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../../docs/TEST_VECTORS-A.md");
    let doc = std::fs::read_to_string(&path).expect("docs/TEST_VECTORS-A.md");
    assert_eq!(
        render().trim(),
        doc.trim(),
        "docs/TEST_VECTORS-A.md no longer matches the code; regenerate it and bump the profile version"
    );
}
