//! Prints the pinned test vectors of docs/TEST_VECTORS.md. Regenerate with
//! `cargo test -p sb-core --release --test vectors -- --ignored --nocapture`.
//! If any value changes, the profile changed.

use ark_ff::{BigInteger, PrimeField};
use sha2::{Digest, Sha256};

use sb_core::address::Network;
use sb_core::envelope::{TransferBody, bytes_to_fr_253};
use sb_core::keys::{Seed, WalletKeys};
use sb_core::note::{NotePlaintext, encrypt_note, note_leaf, nullifier};
use sb_core::recovery::{RecoveryEntry, binding_digest, encrypt_recovery};
use sb_core::tree::{DEPTH, EMPTY_ROOTS};
use sb_primitives::Fr;
use sb_primitives::diversify::diversify_hash;
use sb_primitives::encoding::{fr_to_bytes, point_to_bytes};
use sb_primitives::poseidon::hash;
use sb_primitives::scalar::scalar_to_bytes;
use sb_primitives::tags;

fn h(f: &Fr) -> String {
    hex::encode(fr_to_bytes(f))
}

#[test]
#[ignore]
fn print_vectors() {
    println!("# Test vectors (profile draft v0.1)\n");
    println!(
        "Generated by `crates/sb-core/tests/vectors.rs`. All field elements are 32-byte little-endian hex; points are compressed Jubjub (profile §1).\n"
    );

    println!("## Poseidon\n");
    println!("| Input | Output |\n|---|---|");
    println!(
        "| `PH(0, [0, 0])` | `{}` |",
        h(&hash(Fr::from(0u64), &[Fr::from(0u64), Fr::from(0u64)]))
    );
    println!(
        "| `PH(1, [2, 3, 4])` | `{}` |",
        h(&hash(
            Fr::from(1u64),
            &[Fr::from(2u64), Fr::from(3u64), Fr::from(4u64)]
        ))
    );
    println!("| `E_1 = PH(T_NODE, [0, 0])` | `{}` |", h(&EMPTY_ROOTS[1]));
    println!(
        "| `E_32` (empty tree root) | `{}` |",
        h(&EMPTY_ROOTS[DEPTH])
    );
    println!();

    println!("## Domain tags\n");
    println!("| Tag | Label | `Fr` |\n|---|---|---|");
    for (name, label) in tags::ALL {
        println!(
            "| `{name}` | `{label}` | `{}` |",
            h(&tags::tag(label.as_bytes()))
        );
    }
    println!();

    println!("## DiversifyHash\n");
    println!("| `d` (hex) | Result |\n|---|---|");
    for i in 0u8..6 {
        let mut d = [0u8; 11];
        d[0] = i;
        match diversify_hash(&d) {
            Some(p) => println!(
                "| `{}` | `{}` |",
                hex::encode(d),
                hex::encode(point_to_bytes(&p))
            ),
            None => println!("| `{}` | invalid |", hex::encode(d)),
        }
    }
    println!();

    let seed = Seed([1u8; 32]);
    let k = WalletKeys::from_seed(&seed);
    println!("## Key hierarchy for seed `{}`\n", hex::encode(seed.0));
    println!("| Key | Value |\n|---|---|");
    println!("| `sk_master` | `{}` |", hex::encode(k.sk_master));
    println!(
        "| `sk_spend` (scalar, LE) | `{}` |",
        hex::encode(scalar_to_bytes(&k.sk_spend))
    );
    println!("| `vk_out` | `{}` |", hex::encode(k.ovk.0));
    println!("| `sk_nf` | `{}` |", h(&k.sk_nf));
    println!("| `vk_in` | `{}` |", h(&k.ivk.vk_in));
    println!(
        "| `sk_view` (scalar, LE) | `{}` |",
        hex::encode(scalar_to_bytes(&k.ivk.sk_view))
    );
    let (i, addr) = k.ivk.find_address(0);
    println!("| first valid receive path | `{i}` |");
    println!("| `d` | `{}` |", hex::encode(addr.d));
    println!("| `pk_d` | `{}` |", hex::encode(point_to_bytes(&addr.pk_d)));
    println!("| address (signet) | `{}` |", addr.encode(Network::Signet));
    println!(
        "| address (mainnet) | `{}` |",
        addr.encode(Network::Mainnet)
    );
    println!();

    let pt = NotePlaintext {
        value: 123_456,
        d: addr.d,
        rseed: Fr::from(2u64),
    };
    let (pk_eph, ct) = encrypt_note(&pt, &addr.pk_d).unwrap();
    let const_salt: [u8; 32] = Sha256::digest(b"sb/v1/const_salt/vectors").into();
    let salt_fe = bytes_to_fr_253(&const_salt);
    println!("## Note `(v = 123456, d above, rseed = 2)` to that address\n");
    println!("| Value | Hex |\n|---|---|");
    println!("| `m_0` | `{}` |", h(&pt.m0()));
    println!("| `rho` | `{}` |", h(&pt.rho()));
    println!(
        "| `sk_eph` (scalar, LE) | `{}` |",
        hex::encode(scalar_to_bytes(&pt.sk_eph()))
    );
    println!("| `pk_eph` | `{}` |", hex::encode(point_to_bytes(&pk_eph)));
    println!("| `ct_note` | `{}` |", hex::encode(ct.to_bytes()));
    println!(
        "| `const_salt = SHA-256(\"sb/v1/const_salt/vectors\")` | `{}` |",
        hex::encode(const_salt)
    );
    println!("| `const_salt` as `Fr` | `{}` |", h(&salt_fe));
    println!(
        "| `leaf` with `h_body = 3`, `j = 0` | `{}` |",
        h(&note_leaf(&salt_fe, &Fr::from(3u64), 0, &pk_eph, &ct))
    );
    println!(
        "| `nf` with `pos = 5` | `{}` |",
        h(&nullifier(&k.sk_nf, &pt.rho(), 5))
    );
    println!();

    let entries = [
        RecoveryEntry {
            pk_d: addr.pk_d,
            sk_eph: pt.sk_eph(),
        },
        RecoveryEntry {
            pk_d: addr.pk_d,
            sk_eph: pt.sk_eph(),
        },
    ];
    let digest = binding_digest(&[pk_eph, pk_eph], &[ct, ct]);
    let ct_out = encrypt_recovery(&k.ovk, &digest, &entries);
    let body = TransferBody {
        h_anchor: 100,
        nullifiers: [Fr::from(1u64), Fr::from(2u64)],
        pk_eph: [pk_eph, pk_eph],
        ct_note: [ct, ct],
        ct_out,
    };
    println!("## Transfer body (`h_anchor = 100`, `nf = [1, 2]`, the note above twice)\n");
    println!("| Value | Hex |\n|---|---|");
    println!("| recovery binding digest | `{}` |", hex::encode(digest));
    println!("| `ct_out` | `{}` |", hex::encode(ct_out));
    println!(
        "| `body_bytes` ({} bytes) | `{}` |",
        body.to_bytes().len(),
        hex::encode(body.to_bytes())
    );
    println!(
        "| `h_body` under `const_salt` above | `{}` |",
        h(&body.h_body(&const_salt))
    );
    println!();

    println!("## Groth16 verifying key\n");
    println!(
        "`SHA-256(vk)` for the insecure setup with seed `00…00`: `58b0ee44d0e969f873c0137f364659ac6c8f5878746a1abb2fee1d31befd95fd` (17 public inputs, 84 362 constraints).\n"
    );
    println!(
        "Field modulus check: `q = {}`.",
        hex::encode(Fr::MODULUS.to_bytes_be())
    );
}
