//! Generates the pinned Poseidon constants (profile §2.1) with the Grain-LFSR
//! procedure as implemented by ark-crypto-primitives. Run with
//! `cargo test -p sb-primitives --test gen_poseidon_params -- --ignored --nocapture`
//! and paste the output into `src/poseidon/params.rs`.

use ark_crypto_primitives::sponge::poseidon::find_poseidon_ark_and_mds;
use ark_ff::{BigInteger, PrimeField};
use sb_primitives::Fr;

#[test]
#[ignore]
fn print_params() {
    let (ark, mds) = find_poseidon_ark_and_mds::<Fr>(255, 2, 8, 57, 0);
    assert_eq!(ark.len(), 65);
    assert_eq!(mds.len(), 3);
    let hex = |f: &Fr| hex::encode(f.into_bigint().to_bytes_le());
    println!("// GENERATED by tests/gen_poseidon_params.rs; do not edit.");
    println!("pub const ROUND_CONSTANTS_HEX: [[&str; 3]; 65] = [");
    for row in &ark {
        println!(
            "    [\"{}\", \"{}\", \"{}\"],",
            hex(&row[0]),
            hex(&row[1]),
            hex(&row[2])
        );
    }
    println!("];");
    println!("pub const MDS_HEX: [[&str; 3]; 3] = [");
    for row in &mds {
        println!(
            "    [\"{}\", \"{}\", \"{}\"],",
            hex(&row[0]),
            hex(&row[1]),
            hex(&row[2])
        );
    }
    println!("];");
}
